@dataclass
class StarchSynthesizerState:
    """State of the cell-free starch synthesis system.

    Reference: Cai et al., Science 373:1523 (2021)
    ASAP = Artificial Starch Anabolic Pathway (11 core reactions)
    """
    # Enzyme health (0-1) — enzymes degrade and must be reproduced
    enzyme_health: float = 1.0
    # Enzyme production capacity (DNA templates → fresh enzymes)
    enzyme_dna_templates_intact: float = 1.0  # 0-1, degrades with radiation
    enzyme_production_rate: float = 1.0  # Fraction of nominal

    # Reactor parameters
    num_reactors: int = 4  # Redundant reactors
    reactor_volume_liters: float = 500.0  # Per reactor
    reactor_health: float = 1.0  # Average across all reactors
    temperature_c: float = 30.0  # Optimal: 25-37°C

    # Production rate
    # Cai et al.: 22 nmol CO2/min/mg catalyst = ~0.66 g starch/hr/kg catalyst
    # Lab rate: ~1.58 kg/day/reactor. Engineering scale-up: 10-30% of lab rate.
    # Conservative estimate: 0.3 kg/day/reactor (19% of lab rate)
    # Reference: Typical scale-up losses in cell-free enzymatic processes
    catalyst_mass_kg: float = 100.0
    nominal_rate_kg_per_day: float = 0.3  # Per reactor, conservative scale-up
    actual_rate_kg_per_day: float = 0.0

    # Inputs consumed per kg starch produced
    co2_per_kg_starch: float = 0.73  # Cai et al. (2021) Science 373:1523, ASAP stoichiometry
    h2_per_kg_starch: float = 0.12   # Cai et al. (2021) supplementary Table S2
    h2o_per_kg_starch: float = 0.56  # Cai et al. (2021) supplementary Table S2
    # Cai et al. 2021 *Science* 373 1523 Fig 4: the ASAP cell-
    # free pathway has an end-to-end energy budget of ~4.7 kWh
    # per kg of starch when the hydrogen input is provided by an
    # upstream electrolyser running at 70 % PEM efficiency.
    # Rounded up to 5.0 kWh to include the enzyme reactor
    # thermal regulation load.
    power_per_kg_starch_kwh: float = 5.0

    # Cofactor pool tracking (P2 fix)
    # ASAP pathway requires ATP and NADH recycling. Cofactors degrade
    # and must be regenerated enzymatically. Pool depletion rate-limits
    # starch synthesis even when enzymes are healthy.
    atp_pool_health: float = 1.0     # 0-1, regenerated by ATP synthase
    nadh_pool_health: float = 1.0    # 0-1, regenerated by hydrogenase
    cofactor_regeneration_rate: float = 1.0  # Fraction of nominal


@dataclass
class ProteinSynthesizerState:
    """State of protein synthesis systems (multiple pathways).

    Pathways:
      1. Solein (Solar Foods): CO2 + H2 + electricity → single-cell protein
         - 65% protein, 5-8% fat, 20-25% carbs
         - ~1 kg protein per 17 kWh electricity
      2. Yeast fermentation: CO2 → alcohol → yeast → protein/fat
      3. Spirulina bioreactor: photosynthetic (needs light, but as backup)
    """
    # Solein reactor
    solein_reactor_health: float = 1.0
    # Solar Foods Solein: ~1 kg per 9-17 kWh electricity; 2 kg/day ESTIMATE for ship-scale reactor
    solein_production_kg_per_day: float = 2.0   # ESTIMATE — ship-scale Solein reactor

    # Yeast fermentation
    yeast_culture_health: float = 1.0
    yeast_production_kg_per_day: float = 1.0    # ESTIMATE — yeast bioreactor output

    # Spirulina (backup — needs light)
    spirulina_health: float = 1.0
    spirulina_production_kg_per_day: float = 0.5  # ESTIMATE — backup spirulina bioreactor

    # Combined output
    total_protein_kg_per_day: float = 0.0

    # Input costs
    # Solar Foods LCA: ~9-17 kWh/kg Solein (Näkkilä 2021 Bioresour Technol 342 125978)
    # 2025 update: Solar Foods factory-1 pilot ~10-12 kWh/kg at scale (Järvi 2023 Nature Food 4 930)
    power_per_kg_protein_kwh: float = 17.0     # Näkkilä 2021 Bioresour Technol 342 125978 (upper/conservative)
    co2_per_kg_protein: float = 1.8            # ESTIMATE — CO2 stoichiometry for single-cell protein
    h2_per_kg_protein: float = 0.3             # ESTIMATE — H2 requirement for hydrogenotrophic growth


@dataclass
class FoodSynthesisState:
    """Complete food synthesis system state."""
    starch: StarchSynthesizerState = field(default_factory=StarchSynthesizerState)
    protein: ProteinSynthesizerState = field(default_factory=ProteinSynthesizerState)

    # Vitamin/mineral synthesis
    vitamin_synthesis_health: float = 1.0
    mineral_extraction_health: float = 1.0

    # Overall food production (kg/day)
    total_food_kg_per_day: float = 0.0

    # Resource availability (default for 4 crew; scaled in __init__ by actual crew_size)
    co2_available_kg_per_day: float = 4.0  # crew_size × 1 kg CO2/person/day
    h2o_available_liters_per_day: float = 50.0  # From water recycling
    power_available_kw: float = 100.0  # Allocated to food synthesis

    # Nutritional quality (0-1)
    carb_adequacy: float = 1.0
    protein_adequacy: float = 1.0
    fat_adequacy: float = 1.0
    vitamin_adequacy: float = 1.0
    overall_nutrition: float = 1.0


class FoodSynthesisSimulator:
    """Simulates food synthesis from CO2 + H2O for a generation ship.

    Key advantage over traditional agriculture:
      - No seeds needed (enzymes produced from DNA templates)
      - No grow lights needed (cell-free chemical process)
      - No soil needed (reactor-based)
      - Scales with power, not area
      - Can sustain crew indefinitely if power and enzymes maintained

    Key vulnerabilities:
      - Enzyme degradation (must reproduce from DNA templates)
      - DNA template damage from radiation (the new bottleneck)
      - Reactor contamination
      - Power dependency (no power = no food)
      - Single points of failure in enzyme production pipeline
    """

    def __init__(self, crew_size: int = 4, seed: int | None = None) -> None:
        import random
        self._rng = random.Random(seed)
        self._crew_size = crew_size
        self.state = FoodSynthesisState()
        # Scale CO2 availability to actual crew size (1 kg CO2/person/day)
        # Human CO2 exhalation: ~0.9-1.0 kg/person/day (NASA BVAD NASA/TP-2015-218570)
        self.state.co2_available_kg_per_day = crew_size * 1.0  # NASA BVAD ~1 kg CO2/person/day
        # Daily food need: ~2 kg/person (WHO/FAO protein + energy requirements)
        # WHO/FAO/UNU 2004 Human Energy Requirements (FAO Food and Nutrition Technical Report 1)
        self._daily_need_kg = crew_size * 2.0              # ESTIMATE — ~2 kg/person/day total food
        self._daily_carb_need_kg = crew_size * 0.4         # ESTIMATE — ~400g carbs/person/day
        self._daily_protein_need_kg = crew_size * 0.1      # ESTIMATE — ~100g protein/person/day

    def simulate_year(self, mission_year: float) -> list[dict[str, Any]]:
        """Simulate one year of food synthesis operations."""
        events: list[dict[str, Any]] = []
        s = self.state
        st = s.starch
        pr = s.protein

        # ── Enzyme degradation (thermal + chemical aging) ──
        # Enzymes last ~months in solution; continuous replacement needed
        # 2%/yr baseline ESTIMATE — enzyme half-life ~weeks-months in solution (Daniel 1996)
        st.enzyme_health = max(0.1, st.enzyme_health - 0.02)  # ESTIMATE: 2%/yr enzyme decay

        # DNA template degradation from cosmic radiation (~0.5%/year behind shielding)
        # GCR dose behind shielding ~10 mGy/yr; DNA double-strand breaks ~0.5%/yr (Cucinotta 2014)
        st.enzyme_dna_templates_intact = max(0, st.enzyme_dna_templates_intact - 0.005)  # ESTIMATE: 0.5%/yr

        # Enzyme replacement from DNA templates
        if st.enzyme_dna_templates_intact > 0.1:
            # Can reproduce enzymes — health recovers
            recovery = st.enzyme_dna_templates_intact * st.enzyme_production_rate * 0.05
            st.enzyme_health = min(1.0, st.enzyme_health + recovery)
            self._enzyme_depleted_latched = False
        elif not getattr(self, "_enzyme_depleted_latched", False):
            events.append({
                "year": mission_year,
                "severity": "EMERGENCY",
                "message": f"Enzyme DNA templates critically degraded: {st.enzyme_dna_templates_intact:.0%}. "
                           "Cannot reproduce food synthesis enzymes. Starvation imminent.",
                "subsystem": "food_synthesis",
            })
            self._enzyme_depleted_latched = True

        # ── Cofactor pool degradation (ATP/NADH) ──
        # ATP and NADH are consumed in each ASAP cycle and must be regenerated.
        # Regeneration enzymes (ATP synthase, hydrogenase) degrade independently.
        st.atp_pool_health = max(0.1, st.atp_pool_health - 0.008)
        st.nadh_pool_health = max(0.1, st.nadh_pool_health - 0.006)

        # Cofactor regeneration depends on enzyme health and power availability
        if st.enzyme_dna_templates_intact > 0.2:
            regen = st.cofactor_regeneration_rate * st.enzyme_health * 0.03
            st.atp_pool_health = min(1.0, st.atp_pool_health + regen)
            st.nadh_pool_health = min(1.0, st.nadh_pool_health + regen * 0.8)
        st.cofactor_regeneration_rate = max(0.3, st.cofactor_regeneration_rate - 0.002)

        if min(st.atp_pool_health, st.nadh_pool_health) < 0.3:
            events.append({
                "year": mission_year,
                "severity": "WARNING",
                "message": f"Cofactor pools depleted: ATP={st.atp_pool_health:.0%}, "
                           f"NADH={st.nadh_pool_health:.0%}. Starch synthesis rate-limited.",
                "subsystem": "food_synthesis",
            })

        # ── Reactor degradation ──
        st.reactor_health = max(0.3, st.reactor_health - 0.005)

        # Random reactor failure (1% per year per reactor)
        if self._rng.random() < 0.01 * st.num_reactors:
            st.num_reactors = max(1, st.num_reactors - 1)
            events.append({
                "year": mission_year,
                "severity": "WARNING",
                "message": f"Starch reactor failed. {st.num_reactors} remaining.",
                "subsystem": "food_synthesis",
            })

        # ── Starch production calculation ──
        # Rate = nominal × enzyme_health × reactor_health × (num_reactors/4) × cofactor_bottleneck
        reactor_fraction = st.num_reactors / 4.0
        cofactor_factor = min(st.atp_pool_health, st.nadh_pool_health)
        st.actual_rate_kg_per_day = (
            st.nominal_rate_kg_per_day
            * st.enzyme_health
            * st.reactor_health
            * reactor_fraction
            * cofactor_factor
        )
        daily_starch = st.actual_rate_kg_per_day * st.num_reactors

        # ── Protein production ──
        pr.solein_reactor_health = max(0.2, pr.solein_reactor_health - 0.008)
        pr.yeast_culture_health = max(0.1, pr.yeast_culture_health - 0.005)
        pr.spirulina_health = max(0, pr.spirulina_health - 0.015)  # Needs light, degrades faster

        # Random contamination
        if self._rng.random() < 0.02:
            target = self._rng.choice(["solein", "yeast", "spirulina"])
            if target == "solein":
                pr.solein_reactor_health *= 0.7
            elif target == "yeast":
                pr.yeast_culture_health *= 0.6
            else:
                pr.spirulina_health *= 0.5
            events.append({
                "year": mission_year,
                "severity": "WARNING",
                "message": f"Protein synthesis contamination in {target} reactor.",
                "subsystem": "food_synthesis",
            })

        daily_protein = (
            pr.solein_production_kg_per_day * pr.solein_reactor_health +
            pr.yeast_production_kg_per_day * pr.yeast_culture_health +
            pr.spirulina_production_kg_per_day * pr.spirulina_health
        )
        pr.total_protein_kg_per_day = daily_protein

        # ── Resource constraints ──
        # CO2 available from crew respiration
        co2_needed = (daily_starch * st.co2_per_kg_starch +
                      daily_protein * pr.co2_per_kg_protein)
        co2_limited = min(1.0, s.co2_available_kg_per_day / max(co2_needed, 0.01))

        # Power constraint
        power_needed = (daily_starch * st.power_per_kg_starch_kwh +
                        daily_protein * pr.power_per_kg_protein_kwh) / 24.0  # kW
        power_limited = min(1.0, s.power_available_kw / max(power_needed, 0.01))

        resource_factor = min(co2_limited, power_limited)

        # ── Final food production ──
        s.total_food_kg_per_day = (daily_starch + daily_protein) * resource_factor

        # Nutritional adequacy
        s.carb_adequacy = min(1.0, daily_starch * resource_factor / max(self._daily_carb_need_kg, 0.01))
        s.protein_adequacy = min(1.0, daily_protein * resource_factor / max(self._daily_protein_need_kg, 0.01))
        s.fat_adequacy = min(1.0, pr.yeast_culture_health * 0.8)  # Yeast produces some fat
        s.vitamin_adequacy = s.vitamin_synthesis_health
        s.overall_nutrition = (
            s.carb_adequacy * 0.35 +
            s.protein_adequacy * 0.30 +
            s.fat_adequacy * 0.20 +
            s.vitamin_adequacy * 0.15
        )

        # Vitamin/mineral degradation
        s.vitamin_synthesis_health = max(0.5, s.vitamin_synthesis_health - 0.002)
        s.mineral_extraction_health = max(0.5, s.mineral_extraction_health - 0.001)

        # ── Alerts (latched tiers) ──
        food_ratio = s.total_food_kg_per_day / max(self._daily_need_kg, 0.01)
        if food_ratio < 0.3:
            if not getattr(self, "_food_emerg_latched", False):
                events.append({
                    "year": mission_year,
                    "severity": "EMERGENCY",
                    "message": f"Food synthesis at {food_ratio:.0%} of need. Starvation risk.",
                    "subsystem": "food_synthesis",
                })
                self._food_emerg_latched = True
                self._food_warn_latched = False
        elif food_ratio < 0.7:
            self._food_emerg_latched = False
            if not getattr(self, "_food_warn_latched", False):
                events.append({
                    "year": mission_year,
                    "severity": "WARNING",
                    "message": f"Food synthesis at {food_ratio:.0%} of need. Rationing recommended.",
                    "subsystem": "food_synthesis",
                })
                self._food_warn_latched = True
        else:
            self._food_emerg_latched = False
            self._food_warn_latched = False

        if s.overall_nutrition < 0.5 and not getattr(self, "_food_nutr_latched", False):
            events.append({
                "year": mission_year,
                "severity": "WARNING",
                "message": f"Nutritional quality degraded: {s.overall_nutrition:.0%}. "
                           "Risk of deficiency diseases.",
                "subsystem": "food_synthesis",
            })
            self._food_nutr_latched = True
        elif s.overall_nutrition >= 0.6:
            self._food_nutr_latched = False

        return events

    def get_comparison_with_agriculture(self, years: int = 200) -> dict[str, Any]:
        """Compare food synthesis vs traditional agriculture over time.

        Returns data showing when each system fails and by how much.
        """
        from aria.simulation.interstellar_challenges import FoodCenturySimulator

        # Run agriculture simulation
        agri = FoodCenturySimulator(crew_size=self._crew_size, seed=42)
        # Run synthesis simulation
        synth = FoodSynthesisSimulator(crew_size=self._crew_size, seed=42)

        agri_production = []
        synth_production = []

        for year in range(1, years + 1):
            agri.simulate_year(float(year))
            synth.simulate_year(float(year))

            agri_production.append(agri.food.annual_food_production_kg / 365.0)
            synth_production.append(synth.state.total_food_kg_per_day)

        daily_need = self._crew_size * 2.0

        # Find when each drops below need
        agri_fails_year = None
        synth_fails_year = None
        for i, (a, s) in enumerate(zip(agri_production, synth_production)):
            if a < daily_need and agri_fails_year is None:
                agri_fails_year = i + 1
            if s < daily_need and synth_fails_year is None:
                synth_fails_year = i + 1

        return {
            "agriculture_fails_year": agri_fails_year,
            "synthesis_fails_year": synth_fails_year,
            "agriculture_final_kg_day": agri_production[-1] if agri_production else 0,
            "synthesis_final_kg_day": synth_production[-1] if synth_production else 0,
            "daily_need_kg": daily_need,
            "synthesis_advantage_years": (
                (synth_fails_year or years) - (agri_fails_year or years)
            ),
        }


