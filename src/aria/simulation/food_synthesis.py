"""Food Synthesis Models — solving the Food Century Problem.

The core insight: traditional agriculture (seeds + soil + grow lights) fails after
~50 years on a generation ship. But we don't NEED agriculture.

STARCH SYNTHESIZER (Cai et al., Science 2021):
  - Cell-free chemoenzymatic pathway: CO2 + H2O + H2 → starch
  - 11 enzyme reactions (ASAP = Artificial Starch Anabolic Pathway)
  - 8.5× faster than corn starch production
  - No seeds, no soil, no grow lights, no farming
  - Inputs: CO2 (crew respiration), H2O (recycled), H2 (electrolysis)
  - Reference: Cai et al. "Cell-free chemoenzymatic starch synthesis from CO2"
    Science 373, 1523-1527 (2021). DOI: 10.1126/science.abh4049

PROTEIN SYNTHESIS:
  - Solar Foods "Solein": CO2 + H2 + electricity → single-cell protein (65% protein)
  - Air Company: CO2 + H2 → alcohol → feed edible yeast → protein/fat/carbs
  - Spirulina algae: 60% protein, grows in bioreactor
  - Insect farming: 2× feed conversion efficiency vs cattle

COMPLETE FOOD CHAIN (no agriculture needed):
  1. Electrolysis: H2O → H2 + O2 (O2 for crew, H2 for synthesis)
  2. Starch synthesis: CO2 + H2 → starch (carbohydrates)
  3. Protein synthesis: CO2 + H2 → Solein/yeast (protein + fat)
  4. Mineral extraction: recycled waste → essential minerals
  5. Vitamin synthesis: enzymatic/chemical (already industrial)
  → Complete nutrition from CO2 + H2O + electricity

WHY THIS CHANGES EVERYTHING:
  - No seed viability problem (enzymes can be produced from DNA templates)
  - No grow light problem (no photosynthesis needed)
  - No soil problem (cell-free process)
  - Scales with electrical power, not area
  - Enzyme production from stored DNA → effectively unlimited if DNA preserved
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any

