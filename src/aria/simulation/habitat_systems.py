#  ORCHESTRATOR — runs all three habitat systems together
# ════════════════════════════════════════════════════════════════

class HabitatSystemsOrchestrator:
    """Runs Environmental Control, Recreation & Morale, and Supply Chain
    together with cross-system feedback loops.

    Cross-system interactions:
    - ECLSS filter consumption feeds supply chain depletion
    - Supply chain shortages of filters degrade ECLSS performance
    - ECLSS temperature/air quality affects morale
    - Low morale reduces exercise compliance (recreation -> ECLSS bone density)
    - Manufacturing feedstock depletion limits ECLSS part replacement
    """

    def __init__(self, crew_size: int = 50, seed: int | None = None) -> None:
        self.crew_size = crew_size
        self.eclss = EnvironmentalControlSimulator(crew_size=crew_size, seed=seed)
        self.recreation = RecreationMoraleSimulator(
            crew_size=crew_size,
            seed=seed + 1 if seed is not None else None,
        )
        self.supply_chain = SupplyChainSimulator(
            crew_size=crew_size,
            seed=seed + 2 if seed is not None else None,
        )

    def simulate_year(self, mission_year: float) -> list[dict[str, Any]]:
        events: list[dict[str, Any]] = []

        # Run subsystems
        events.extend(self.eclss.simulate_year(mission_year))
        events.extend(self.recreation.simulate_year(mission_year))
        events.extend(self.supply_chain.simulate_year(mission_year))

        # --- Cross-system feedback ---
        eclss_s = self.eclss.state
        rec_s = self.recreation.state
        sc_s = self.supply_chain.state

        # ECLSS air quality affects morale
        if eclss_s.habitat_zone.co2_ppm > 1000:
            co2_penalty = (eclss_s.habitat_zone.co2_ppm - 1000) / 5000
            rec_s.crew_morale = max(0.1, rec_s.crew_morale - co2_penalty)

        # Temperature discomfort affects morale
        temp_deviation = abs(
            eclss_s.habitat_zone.temperature_c
            - eclss_s.habitat_zone.target_temp_c
        )
        if temp_deviation > 3:
            rec_s.crew_morale = max(
                0.1, rec_s.crew_morale - temp_deviation * 0.01
            )

        # Low morale reduces exercise compliance
        if rec_s.crew_morale < 0.4:
            rec_s.exercise_compliance_rate = max(
                0.3, rec_s.exercise_compliance_rate - 0.05
            )

        # Supply chain filter stock affects ECLSS (latched)
        hepa_item = sc_s.items.get("hepa_filters")
        if hepa_item and hepa_item.quantity <= 0:
            eclss_s.hepa_filter_health = max(
                0.1, eclss_s.hepa_filter_health - 0.1
            )
            if not getattr(self, "_hepa_zero_latched", False):
                events.append({
                    "year": mission_year, "severity": "CRITICAL",
                    "message": (
                        "No HEPA filter stock — ECLSS air filtration degrading"
                    ),
                    "subsystem": "habitat_crosslink",
                })
                self._hepa_zero_latched = True
        elif hepa_item and hepa_item.quantity > 0:
            self._hepa_zero_latched = False

        carbon_item = sc_s.items.get("activated_carbon_kg")
        if carbon_item and carbon_item.quantity <= 0:
            eclss_s.activated_carbon_capacity = max(
                0.1, eclss_s.activated_carbon_capacity - 0.1
            )

        return events
