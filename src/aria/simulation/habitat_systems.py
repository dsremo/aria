class SupplyChainSimulator:
    """Simulates consumable tracking, depletion, manufacturing, and allocation.

    On a generation ship there is no resupply. Everything is either:
    1. Stored from launch (finite, eventually runs out)
    2. Manufactured onboard (limited by feedstock and printer capacity)
    3. Recycled (imperfect, always some loss)

    The critical path — whichever item runs out first — determines
    mission viability. This simulator tracks that constraint.
    """

    AUDIT_INTERVAL_YEARS = 1

    def __init__(
        self,
        crew_size: int = 50,
        seed: int | None = None,
        custom_inventory: list[dict[str, Any]] | None = None,
    ) -> None:
        self._rng = random.Random(seed)
        self.crew_size = crew_size
        self.state = SupplyChainState()
        self._init_inventory(custom_inventory or _DEFAULT_INVENTORY)

    def _init_inventory(self, catalog: list[dict[str, Any]]) -> None:
        for spec in catalog:
            item = InventoryItem(
                name=spec["name"],
                category=spec.get("category", "general"),
                quantity=spec.get("quantity", 0),
                unit=spec.get("unit", "units"),
                depletion_rate_per_year=spec.get("depletion_rate_per_year", 0),
                reorder_point=spec.get("reorder_point", 0),
                manufacturing_lead_time_days=spec.get(
                    "manufacturing_lead_time_days", 7
                ),
                substitution_available=spec.get("substitution_available", False),
                substitution_name=spec.get("substitution_name", ""),
                substitution_efficiency=spec.get("substitution_efficiency", 0.8),
                priority=spec.get("priority", 2),
            )
            self.state.items[item.name] = item
        self.state.total_items_tracked = len(self.state.items)

    def simulate_year(self, mission_year: float) -> list[dict[str, Any]]:
        events: list[dict[str, Any]] = []
        s = self.state

        # --- 3D printer degradation ---
        s.printer_health = max(
            0.2, s.printer_health - 0.005 - self._rng.uniform(0, 0.002)
        )
        s.manufacturing_capacity = s.printer_health * min(
            1.0,
            s.feedstock_metal_kg / 1000,
            s.feedstock_polymer_kg / 500,
        )

        # --- Deplete each item ---
        critical_count = 0
        below_reorder = 0
        min_years_remaining = float("inf")
        critical_item_name = ""

        for item in s.items.values():
            # Stochastic consumption: base rate + noise + crew size scaling
            crew_factor = self.crew_size / 50.0
            consumption = (
                item.depletion_rate_per_year * crew_factor
                * (1.0 + self._rng.gauss(0, 0.05))
            )
            consumption = max(0, consumption)

            # Rationing reduces consumption
            if s.allocation_mode == "rationing":
                if item.priority >= 3:
                    consumption *= 0.5
                elif item.priority == 2:
                    consumption *= 0.8
            elif s.allocation_mode == "emergency":
                if item.priority >= 3:
                    consumption *= 0.1
                elif item.priority == 2:
                    consumption *= 0.5

            item.quantity = max(0, item.quantity - consumption)
            item.cumulative_consumed += consumption
            item.historical_rates.append(consumption)
            # Keep last 20 years of history
            if len(item.historical_rates) > 20:
                item.historical_rates = item.historical_rates[-20:]

            # Manufacturing resupply for items that can be made
            if (
                item.quantity < item.reorder_point
                and item.manufacturing_lead_time_days > 0
                and s.manufacturing_capacity > 0.3
            ):
                # Produce based on capacity and lead time
                production_rate = (
                    365.0 / max(1, item.manufacturing_lead_time_days)
                    * s.manufacturing_capacity * 0.3
                )
                produced = min(production_rate, item.reorder_point - item.quantity)
                if produced > 0:
                    item.quantity += produced
                    # Feedstock consumption per manufactured unit.
                    # Based on the item's own ``mass_per_unit_kg``
                    # field with a 50/30 metal/polymer split
                    # typical of ISS spare parts (NASA/TM-2018-219855
                    # "In-Space Manufacturing" Table 2). Previously
                    # hard-coded to 0.1 kg/unit which over- or
                    # under-counted material draw depending on the
                    # item mass.
                    unit_mass = getattr(item, "mass_per_unit_kg", 0.1)
                    s.feedstock_metal_kg = max(
                        0.0, s.feedstock_metal_kg - produced * unit_mass * 0.5
                    )
                    s.feedstock_polymer_kg = max(
                        0.0, s.feedstock_polymer_kg - produced * unit_mass * 0.3
                    )

            # Track critical status (latched per-item to avoid yearly spam)
            if not hasattr(self, "_stockout_latched"):
                self._stockout_latched = set()
            if not hasattr(self, "_reorder_latched"):
                self._reorder_latched = set()
            if item.quantity <= 0:
                critical_count += 1
                if item.priority == 1 and item.name not in self._stockout_latched:
                    events.append({
                        "year": mission_year, "severity": "EMERGENCY",
                        "message": (
                            f"STOCKOUT: {item.name} — zero remaining. "
                            f"Priority {item.priority} "
                            f"({'life-critical' if item.priority == 1 else 'important'})"
                        ),
                        "subsystem": "supply_chain",
                    })
                    self._stockout_latched.add(item.name)
            else:
                self._stockout_latched.discard(item.name)
                if item.quantity < item.reorder_point:
                    below_reorder += 1
                    if item.priority == 1 and item.name not in self._reorder_latched:
                        events.append({
                            "year": mission_year, "severity": "WARNING",
                            "message": (
                                f"{item.name} below reorder: {item.quantity:.0f} "
                                f"{item.unit} (reorder at {item.reorder_point:.0f})"
                            ),
                            "subsystem": "supply_chain",
                        })
                        self._reorder_latched.add(item.name)
                elif item.quantity >= item.reorder_point * 1.5:
                    self._reorder_latched.discard(item.name)

            # Years remaining for this item
            if item.depletion_rate_per_year > 0:
                yrs = item.quantity / (item.depletion_rate_per_year * crew_factor)
                if yrs < min_years_remaining:
                    min_years_remaining = yrs
                    critical_item_name = item.name

        s.critical_shortage_count = critical_count
        s.items_below_reorder = below_reorder
        s.years_of_supply_remaining = (
            min_years_remaining if min_years_remaining < float("inf") else 999
        )

        # --- Annual audit ---
        if mission_year % self.AUDIT_INTERVAL_YEARS < 1:
            discrepancies = 0
            for item in s.items.values():
                # Simulate audit: small chance of finding discrepancy
                if self._rng.random() < 0.05:
                    discrepancy_pct = self._rng.uniform(0.01, 0.05)
                    item.quantity *= (1 - discrepancy_pct)
                    discrepancies += 1
                item.last_audit_year = mission_year
            s.audit_discrepancy_rate = discrepancies / max(1, s.total_items_tracked)
            if discrepancies > 0:
                events.append({
                    "year": mission_year, "severity": "NOMINAL",
                    "message": (
                        f"Annual audit: {discrepancies} discrepancies found "
                        f"across {s.total_items_tracked} item categories"
                    ),
                    "subsystem": "supply_chain",
                })

        # --- Allocation mode changes ---
        if s.years_of_supply_remaining < 2 and s.allocation_mode == "normal":
            s.allocation_mode = "rationing"
            events.append({
                "year": mission_year, "severity": "CRITICAL",
                "message": (
                    f"RATIONING activated — critical path item "
                    f"'{critical_item_name}' at "
                    f"{s.years_of_supply_remaining:.1f} years supply"
                ),
                "subsystem": "supply_chain",
            })
        elif s.years_of_supply_remaining < 0.5 and s.allocation_mode != "emergency":
            s.allocation_mode = "emergency"
            events.append({
                "year": mission_year, "severity": "EMERGENCY",
                "message": (
                    f"EMERGENCY allocation — '{critical_item_name}' "
                    f"at {s.years_of_supply_remaining:.2f} years. "
                    "Non-essential consumption halted."
                ),
                "subsystem": "supply_chain",
            })
        elif s.years_of_supply_remaining > 5 and s.allocation_mode != "normal":
            s.allocation_mode = "normal"
            events.append({
                "year": mission_year, "severity": "NOMINAL",
                "message": "Supply levels restored — normal allocation resumed",
                "subsystem": "supply_chain",
            })

        # --- Feedstock warnings (latched) ---
        if s.feedstock_metal_kg < 500 and not getattr(self, "_metal_low_latched", False):
            events.append({
                "year": mission_year, "severity": "CRITICAL",
                "message": (
                    f"Metal feedstock low: {s.feedstock_metal_kg:.0f} kg — "
                    "manufacturing capacity will collapse"
                ),
                "subsystem": "supply_chain",
            })
            self._metal_low_latched = True
        elif s.feedstock_metal_kg >= 750:
            self._metal_low_latched = False

        if s.feedstock_polymer_kg < 300 and not getattr(self, "_polymer_low_latched", False):
            events.append({
                "year": mission_year, "severity": "CRITICAL",
                "message": (
                    f"Polymer feedstock low: {s.feedstock_polymer_kg:.0f} kg — "
                    "3D printing limited"
                ),
                "subsystem": "supply_chain",
            })
            self._polymer_low_latched = True
        elif s.feedstock_polymer_kg >= 450:
            self._polymer_low_latched = False

        # --- Printer health (latched) ---
        if s.printer_health < 0.4 and not getattr(self, "_sc_printer_latched", False):
            events.append({
                "year": mission_year, "severity": "WARNING",
                "message": (
                    f"3D printer fleet health {s.printer_health:.0%} — "
                    "manufacturing throughput degraded"
                ),
                "subsystem": "supply_chain",
            })
            self._sc_printer_latched = True
        elif s.printer_health >= 0.5:
            self._sc_printer_latched = False

        return events

    def get_critical_path(self) -> tuple[str, float]:
        """Return the item name and years until stockout for the critical path."""
        min_years = float("inf")
        critical = ""
        crew_factor = self.crew_size / 50.0
        for item in self.state.items.values():
            if item.depletion_rate_per_year > 0:
                yrs = item.quantity / (item.depletion_rate_per_year * crew_factor)
                if yrs < min_years:
                    min_years = yrs
                    critical = item.name
        return critical, min_years

    def get_category_summary(self) -> dict[str, dict[str, float]]:
        """Return summary statistics grouped by inventory category."""
        summary: dict[str, dict[str, float]] = {}
        for item in self.state.items.values():
            cat = item.category
            if cat not in summary:
                summary[cat] = {"total_quantity": 0, "total_consumed": 0, "count": 0}
            summary[cat]["total_quantity"] += item.quantity
            summary[cat]["total_consumed"] += item.cumulative_consumed
            summary[cat]["count"] += 1
        return summary


