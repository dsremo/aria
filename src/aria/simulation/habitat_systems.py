"""Habitat Systems — Environmental Control, Recreation & Morale, Supply Chain.

Three mission-critical subsystems for the generation ship habitat:

1. ENVIRONMENTAL CONTROL (HVAC + Atmosphere)
   Temperature: 18-26C target, waste heat from equipment, radiator rejection.
   Humidity: 40-60% RH target, condensation in rotating habitat from Coriolis.
   Pressure: 101.3 kPa (1 atm), slow leak from micrometeorite impacts.
   CO2 scrubbing: LiOH canisters (consumable) + Sabatier reactor (catalytic).
   O2 generation: water electrolysis + plant photosynthesis contribution.
   Trace gas removal: TCCS (activated carbon + catalytic oxidizer) for VOC,
     ammonia, formaldehyde, CO from equipment off-gassing.
   Air circulation: forced-air ducting, Coriolis deflects airflow in rotating
     habitat sections (radial flow curves ~3 degrees per m/s at 2 RPM).
   HEPA filters: 99.97% at 0.3 um, media degrades from humidity + particulates.
   Activated carbon beds: finite adsorption capacity, regenerated by heating.
   Zones: habitat (21C, 50% RH, strict), industrial (15-30C, relaxed),
     agricultural (22C, 63% RH, ~1060 ppm CO2 — EDEN ISS 2020 measured baseline).

   Reference: ISS ECLSS architecture, Wieland (1998) "Designing for Human
   Presence in Space", NASA TCCS performance data, Coriolis in O'Neill
   cylinder analysis (Johnson & Holbrow 1977).

2. RECREATION & MORALE
   VR environments: forests, oceans, historical cities — novelty generation
     counters chronic boredom that is the #1 psychological risk on long missions.
   Sports: adapted for 0.56g (basketball arc changes, swimming works fine,
     volleyball floatier, running requires treadmill belt adjustment).
   Arts: music (instruments last centuries if maintained), painting, theater,
     creative writing. Culture preservation is not optional — it is structural.
   Library: glass archive (fused silica, 10^8 year lifetime) + digital + physical.
   Gardens: decorative greenspace separate from agriculture — psychological
     benefit of natural environments (biophilia, Kaplan 1995).
   Social events: festivals, holidays, ceremonies — scheduled community bonding.
   Exercise: 2 hours/day mandatory in 0.56g to prevent bone loss (0.56g still
     causes ~0.5%/month bone mineral density loss without countermeasures).
   VR hardware: headset lenses scratch, OLED pixels burn in, processors degrade
     from radiation bit-flips. 5-year replacement cycle.
   Morale impact: recreation quality is the primary driver of crew_morale,
     which feeds back into productivity, conflict rate, and birth rate.

   Reference: Kanas (2015) psychology of space exploration, Stuster (2010)
   "Bold Endeavors", ISS crew behavioral health program, Antarctic winter-over
   analog studies (Palinkas 2003).

3. SUPPLY CHAIN & INVENTORY
   Track ALL consumables: quantity, depletion rate, reorder point, lead time.
   Categories: medical supplies, mechanical parts, electronic components,
     raw materials, food stores, water reserves, fuel, non-lethal ammunition.
   Strategy: deep stockpile, NOT just-in-time (JIT on a ship = death when
     supply chain has zero external resupply).
   Critical path: which item reaches zero first? That's the mission constraint.
   Manufacturing lead time: 3D printing replacement parts takes hours to days
     depending on complexity. Feedstock (metal powder, polymer filament) is
     the actual bottleneck.
   Substitution: if item A unavailable, can item B substitute? Substitution
     graph with compatibility scores.
   Inventory audit: annual physical count vs digital records. Discrepancies
     flag theft, measurement error, or unlogged consumption.
   Priority allocation: during shortages, life-critical items (medical, food,
     air filters) get 100% allocation before anything else.
   Historical tracking: consumption history enables trend prediction and
     early warning of accelerating depletion.

   Reference: NASA ISS logistics model, submarine supply management (USN),
   Sheffi (2005) supply chain resilience, Beer Game dynamics.
"""

