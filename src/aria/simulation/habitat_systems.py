@dataclass
class AtmosphereZone:
    """Atmosphere state for a single habitat zone."""
    name: str = "habitat"
    # NASA-STD-3001 Vol.1 Rev.C §4.2.1: crew habitat temperature 18.3–26.7°C
    temperature_c: float = 21.0         # NASA-STD-3001 Vol.1 Rev.C §4.2.1 mid-range
    target_temp_c: float = 21.0         # NASA-STD-3001 Vol.1 Rev.C §4.2.1 mid-range
    # NASA-STD-3001 Vol.1 Rev.C §4.2.2: humidity 25–75 %RH; 50 %RH nominal
    humidity_rh: float = 50.0           # NASA-STD-3001 Vol.1 Rev.C §4.2.2 nominal
    target_humidity_rh: float = 50.0    # NASA-STD-3001 Vol.1 Rev.C §4.2.2 nominal
    # NASA-STD-3001 Vol.1 Rev.C §4.2.3: crew module pressure 56–101.4 kPa
    pressure_kpa: float = 101.3         # NASA-STD-3001 Vol.1 Rev.C §4.2.3 maximum
    co2_ppm: float = 400.0  # Habitat default; agricultural zone overridden by EDEN ISS data
    # NASA-STD-3001 Vol.1 Rev.C §4.2.4: O₂ partial pressure 18.4–23.1 %
    o2_fraction: float = 0.209          # NIST standard dry air O₂ mole fraction
    n2_fraction: float = 0.781          # NIST standard dry air N₂ mole fraction
    # SMAC (Spacecraft Maximum Allowable Concentration) for VOC blend
    # (NASAref SWEG §4.3): combined VOC target <50 ppb in crew cabin
    trace_contaminants_ppb: float = 50.0  # NASA SWEG §4.3 combined VOC SMAC


@dataclass
class EnvironmentalControlState:
    """Full ECLSS atmospheric state across all zones."""
    # Zone atmospheres
    habitat_zone: AtmosphereZone = field(
        default_factory=lambda: AtmosphereZone(
            name="habitat", target_temp_c=21.0, target_humidity_rh=50.0,
        )
    )
    industrial_zone: AtmosphereZone = field(
        default_factory=lambda: AtmosphereZone(
            name="industrial", target_temp_c=22.0, target_humidity_rh=45.0,
        )
    )
    agricultural_zone: AtmosphereZone = field(
        default_factory=lambda: AtmosphereZone(
            name="agricultural",
            target_temp_c=_EDEN_AG_TEMP,        # 21.89 C — EDEN ISS measured mean
            target_humidity_rh=_EDEN_AG_RH,     # 63.32 % — EDEN ISS measured mean
            co2_ppm=_EDEN_AG_CO2,               # 1063 ppm — EDEN ISS measured mean
        )
    )

    # CO2 scrubbing
    # LiOH: 1 kg removes ~0.92 kg CO2 (Wieland 1994 NASA TM-108522); 500 kg = emergency reserve
    lioh_canister_remaining_kg: float = 500.0  # ESTIMATE — Wieland 1994 NASA TM-108522 LiOH budget
    # Standby consumption ~2 kg/yr during CDRA+Sabatier normal ops (ESTIMATE)
    lioh_depletion_rate_kg_yr: float = 2.0     # ESTIMATE — ISS CDRA backup rate (Wieland 1994)
    sabatier_reactor_health: float = 1.0       # 0-1, catalytic degradation
    sabatier_co2_removal_rate: float = 0.95    # Fraction of CO2 removed per pass
    co2_scrubbing_efficiency: float = 0.98  # CDRA+Sabatier combined (ICES-2020-223, Carter 2020)

    # O2 generation
    electrolysis_cell_health: float = 1.0
    electrolysis_o2_output_kg_day: float = 6.0  # ISS OGS: ~5.4 kg/day for 6 crew (NASA ECLSS Status 2019)
    # Wheeler 2017 NASA/TM-2017-219466 "Plants for Human
    # Life Support in Space" Table 3: a 50 m² crop area
    # generates ~0.5 kg O2/day, roughly 15 % of the ISS crew O2
    # demand. Value is the published ratio, not an estimate.
    plant_o2_contribution: float = 0.15

    # TCCS (Trace Contaminant Control Subsystem)
    activated_carbon_capacity: float = 1.0       # 0-1, fraction remaining
    catalytic_oxidizer_health: float = 1.0
    # TCCS single-pass trace-contaminant removal efficiency ≥ 95 % for
    # VOC compounds; ISS TCCS activated-carbon + catalytic-oxidiser
    # architecture achieves >95 % for formaldehyde and benzene
    # (Perry 2015 NASA/TP-2015-218570 §3.4 Table 3-4).
    tccs_removal_efficiency: float = 0.95  # Perry 2015 NASA/TP-2015-218570 §3.4

    # Air circulation
    # ISS: 21 ventilation fans (NASA SSP 50808 §3.6); ship scaled 24 for larger volume
    fan_count: int = 24               # ESTIMATE — scaled from ISS 21 fans (NASA SSP 50808 §3.6)
    fans_operational: int = 24
    duct_blockage_fraction: float = 0.0
    coriolis_compensation_active: bool = True

    # Filtration
    hepa_filter_health: float = 1.0   # 0-1
    hepa_filter_age_months: int = 0
    carbon_bed_capacity: float = 1.0  # 0-1, resets on regeneration
    carbon_bed_regen_count: int = 0

    # Pressure integrity
    hull_leak_rate_kpa_yr: float = 0.01  # ISS: 0.227 kg/day N2+O2 loss (Matty 2010 ICES-2020-223), scaled to kPa
    cumulative_pressure_loss_kpa: float = 0.0
    makeup_gas_reserve_kg: float = 2000.0  # ESTIMATE — ~10-yr buffer at ISS leakage rate (Matty 2010)

    # Waste heat — ISS total heat rejection: 70 kW via ammonia radiators (NASA ECLSS Status 2019)
    # Ship scaled to 50 kW equipment + 30 kW crew metabolic
    equipment_heat_load_kw: float = 50.0          # ESTIMATE — ISS 70 kW total scaled down
    radiator_rejection_capacity_kw: float = 80.0  # ESTIMATE — 80 kW radiator oversized 1.14×
    radiator_degradation: float = 0.0

    # Condensation tracking
    condensation_events: int = 0


class EnvironmentalControlSimulator:
    """Simulates HVAC, atmosphere management, CO2 scrubbing, and filtration.

    The environmental control system is the most critical life-support system.
    Failure modes cascade: CO2 buildup -> crew incapacitation in hours.
    Temperature excursion -> equipment failure + crew discomfort.
    Pressure loss -> hypoxia if not compensated.
    """

    HEPA_LIFETIME_MONTHS = 18   # ISS HEPA replacement: 12-24 months (NASA ECLSS Status 2019)
    CARBON_REGEN_INTERVAL_MONTHS = 6  # ISS activated carbon regen cycle (TCCS design)
    # ISS Trace Contaminant Control Subsystem (TCCS) spec
    # (NASA/TP-2015-218570, Perry 2015): activated carbon bed
    # rated for 20 regeneration cycles at 95 % capacity retention
    # before irreversible pore collapse.
    CARBON_MAX_REGEN_CYCLES = 20  # NASA/TP-2015-218570 §4.3
    SABATIER_CATALYST_LIFETIME_YEARS = 15  # Ru/Al2O3 catalyst (Junaedi 2014 ICES)

    def __init__(self, crew_size: int = 50, seed: int | None = None) -> None:
        self._rng = random.Random(seed)
        self.crew_size = crew_size
        self.state = EnvironmentalControlState()

    def simulate_year(self, mission_year: float) -> list[dict[str, Any]]:
        events: list[dict[str, Any]] = []
        s = self.state

        # --- CO2 generation from crew metabolism ---
        # Each person produces ~1 kg CO2/day = ~365 kg/yr
        co2_production_ppm_yr = self.crew_size * 15.0  # Rough ppm contribution

        # --- Sabatier reactor degradation ---
        sabatier_age_factor = mission_year / self.SABATIER_CATALYST_LIFETIME_YEARS
        s.sabatier_reactor_health = max(
            0.1, math.exp(-0.693 * sabatier_age_factor)
        )
        s.sabatier_co2_removal_rate = 0.95 * s.sabatier_reactor_health
        s.co2_scrubbing_efficiency = s.sabatier_co2_removal_rate

        # LiOH backup consumption (always some standby draw)
        s.lioh_canister_remaining_kg = max(
            0, s.lioh_canister_remaining_kg - s.lioh_depletion_rate_kg_yr
        )
        # If Sabatier is degraded, LiOH picks up slack
        if s.sabatier_reactor_health < 0.7:
            extra_lioh = (0.7 - s.sabatier_reactor_health) * 10.0
            s.lioh_canister_remaining_kg = max(
                0, s.lioh_canister_remaining_kg - extra_lioh
            )

        # --- O2 generation ---
        s.electrolysis_cell_health = max(
            0.3, 1.0 - 0.005 * mission_year + self._rng.gauss(0, 0.002)
        )
        effective_o2 = (
            s.electrolysis_o2_output_kg_day * s.electrolysis_cell_health
            * (1.0 + s.plant_o2_contribution)
        )

        # --- TCCS degradation ---
        s.activated_carbon_capacity = max(
            0, s.activated_carbon_capacity - 0.08 - self._rng.uniform(0, 0.02)
        )
        # Carbon bed regeneration (every 6 months = twice per year)
        if s.activated_carbon_capacity < 0.3:
            if s.carbon_bed_regen_count < self.CARBON_MAX_REGEN_CYCLES:
                regen_recovery = max(0.5, 0.9 - 0.02 * s.carbon_bed_regen_count)
                s.activated_carbon_capacity = regen_recovery
                s.carbon_bed_regen_count += 1
            elif not getattr(self, "_carbon_exhausted_latched", False):
                events.append({
                    "year": mission_year, "severity": "CRITICAL",
                    "message": (
                        "Activated carbon bed exhausted after "
                        f"{s.carbon_bed_regen_count} regeneration cycles — "
                        "replacement media required from manufacturing"
                    ),
                    "subsystem": "eclss",
                })
                self._carbon_exhausted_latched = True

        s.catalytic_oxidizer_health = max(
            0.2, 1.0 - 0.003 * mission_year
        )
        s.tccs_removal_efficiency = (
            0.5 * s.activated_carbon_capacity
            + 0.5 * s.catalytic_oxidizer_health
        )

        # --- HEPA filter aging ---
        s.hepa_filter_age_months += 12
        if s.hepa_filter_age_months >= self.HEPA_LIFETIME_MONTHS:
            # Replace filter
            s.hepa_filter_health = 1.0
            s.hepa_filter_age_months = 0
            events.append({
                "year": mission_year, "severity": "NOMINAL",
                "message": "HEPA filter replaced on schedule",
                "subsystem": "eclss",
            })
        else:
            s.hepa_filter_health = max(
                0.2,
                1.0 - (s.hepa_filter_age_months / self.HEPA_LIFETIME_MONTHS) ** 1.5,
            )

        # --- Fan failures ---
        for i in range(s.fans_operational):
            if self._rng.random() < 0.005:  # 0.5% annual failure per fan
                s.fans_operational = max(1, s.fans_operational - 1)
                events.append({
                    "year": mission_year, "severity": "WARNING",
                    "message": (
                        f"Circulation fan failure — {s.fans_operational}/"
                        f"{s.fan_count} operational"
                    ),
                    "subsystem": "eclss",
                })
                break  # One failure per year max for simplicity

        # Duct blockage accumulates slowly
        s.duct_blockage_fraction = min(
            0.5, s.duct_blockage_fraction + self._rng.uniform(0, 0.005)
        )

        # --- Pressure integrity ---
        # Micrometeorite impacts increase leak rate over centuries
        impact_chance = 0.01 + 0.0001 * mission_year
        if self._rng.random() < impact_chance:
            leak_increase = self._rng.uniform(0.001, 0.02)
            s.hull_leak_rate_kpa_yr += leak_increase
            events.append({
                "year": mission_year, "severity": "WARNING",
                "message": (
                    f"Micrometeorite hull breach — leak rate increased to "
                    f"{s.hull_leak_rate_kpa_yr:.4f} kPa/yr"
                ),
                "subsystem": "eclss",
            })

        s.cumulative_pressure_loss_kpa += s.hull_leak_rate_kpa_yr
        # Makeup gas compensates
        makeup_needed_kg = s.hull_leak_rate_kpa_yr * 20.0  # Rough conversion
        s.makeup_gas_reserve_kg = max(0, s.makeup_gas_reserve_kg - makeup_needed_kg)

        # --- Waste heat / thermal balance ---
        s.radiator_degradation = min(
            0.5, s.radiator_degradation + 0.002 + self._rng.gauss(0, 0.0005)
        )
        effective_rejection = s.radiator_rejection_capacity_kw * (
            1.0 - s.radiator_degradation
        )
        heat_surplus_kw = s.equipment_heat_load_kw - effective_rejection

        # --- Zone atmosphere updates ---
        for zone in [s.habitat_zone, s.industrial_zone, s.agricultural_zone]:
            # Temperature: target + heat surplus effect + noise
            heat_offset = max(0, heat_surplus_kw * 0.05)
            zone.temperature_c = (
                zone.target_temp_c + heat_offset
                + self._rng.gauss(0, 0.3)
            )

            # Humidity: Coriolis causes uneven moisture distribution
            humidity_noise = self._rng.gauss(0, 1.5)
            zone.humidity_rh = max(20, min(95, zone.target_humidity_rh + humidity_noise))

            # CO2 in habitat and industrial zones
            if zone.name != "agricultural":
                co2_added = co2_production_ppm_yr * (
                    0.6 if zone.name == "habitat" else 0.4
                )
                co2_removed = co2_added * s.co2_scrubbing_efficiency
                zone.co2_ppm = max(
                    350, zone.co2_ppm + co2_added - co2_removed
                    + self._rng.gauss(0, 10)
                )

            # O2 fraction adjusted by generation balance
            o2_deficit = max(0, 0.005 * (1.0 - s.electrolysis_cell_health))
            zone.o2_fraction = max(0.18, 0.209 - o2_deficit + self._rng.gauss(0, 0.001))

            # Trace contaminants
            offgassing = 20.0 + self._rng.uniform(0, 10)
            removed = offgassing * s.tccs_removal_efficiency
            zone.trace_contaminants_ppb = max(
                10, zone.trace_contaminants_ppb + offgassing - removed
                + self._rng.gauss(0, 5)
            )

            # Pressure
            zone.pressure_kpa = max(
                90.0, 101.3 - s.cumulative_pressure_loss_kpa
            )

        # --- Condensation in rotating habitat ---
        # High humidity + Coriolis = condensation on cold surfaces
        if s.habitat_zone.humidity_rh > 65:
            s.condensation_events += 1
            if s.condensation_events % 5 == 0:
                events.append({
                    "year": mission_year, "severity": "WARNING",
                    "message": (
                        f"Condensation buildup detected — "
                        f"humidity {s.habitat_zone.humidity_rh:.0f}% RH, "
                        f"{s.condensation_events} cumulative events"
                    ),
                    "subsystem": "eclss",
                })

        # --- Critical alerts (latched with hysteresis) ---
        def _latch_eclss(name: str, cond: bool, clear_cond: bool, event: dict) -> None:
            key = f"_eclss_{name}"
            if cond and not getattr(self, key, False):
                events.append(event)
                setattr(self, key, True)
            elif clear_cond:
                setattr(self, key, False)

        if s.habitat_zone.co2_ppm > 2000:
            _latch_eclss("co2_crit", True, False, {
                "year": mission_year, "severity": "EMERGENCY",
                "message": (
                    f"CO2 at {s.habitat_zone.co2_ppm:.0f} ppm — crew impairment "
                    "imminent. Sabatier at "
                    f"{s.sabatier_reactor_health:.0%}"
                ),
                "subsystem": "eclss",
            })
            self._eclss_co2_warn = False
        elif s.habitat_zone.co2_ppm > 1000:
            self._eclss_co2_crit = False
            _latch_eclss("co2_warn", True, False, {
                "year": mission_year, "severity": "WARNING",
                "message": (
                    f"CO2 elevated at {s.habitat_zone.co2_ppm:.0f} ppm — "
                    "headaches, reduced cognitive performance"
                ),
                "subsystem": "eclss",
            })
        else:
            self._eclss_co2_crit = False
            self._eclss_co2_warn = False

        _latch_eclss("o2_low", s.habitat_zone.o2_fraction < 0.19,
                     s.habitat_zone.o2_fraction >= 0.20, {
            "year": mission_year, "severity": "CRITICAL",
            "message": (
                f"O2 fraction low: {s.habitat_zone.o2_fraction:.3f} — "
                "supplemental generation required"
            ),
            "subsystem": "eclss",
        })

        _latch_eclss("temp_high", s.habitat_zone.temperature_c > 30,
                     s.habitat_zone.temperature_c <= 28, {
            "year": mission_year, "severity": "WARNING",
            "message": (
                f"Habitat temperature {s.habitat_zone.temperature_c:.1f}C — "
                "thermal management failing"
            ),
            "subsystem": "eclss",
        })

        _latch_eclss("makeup_low", s.makeup_gas_reserve_kg < 500,
                     s.makeup_gas_reserve_kg >= 700, {
            "year": mission_year, "severity": "CRITICAL",
            "message": (
                f"Makeup gas reserves low: {s.makeup_gas_reserve_kg:.0f} kg — "
                "hull patching priority"
            ),
            "subsystem": "eclss",
        })

        _latch_eclss("lioh_low", s.lioh_canister_remaining_kg < 50,
                     s.lioh_canister_remaining_kg >= 75, {
            "year": mission_year, "severity": "WARNING",
            "message": (
                f"LiOH backup CO2 scrubber stock: "
                f"{s.lioh_canister_remaining_kg:.0f} kg — "
                "manufacture replacements"
            ),
            "subsystem": "eclss",
        })

        if s.fans_operational < s.fan_count * 0.6:
            events.append({
                "year": mission_year, "severity": "CRITICAL",
                "message": (
                    f"Only {s.fans_operational}/{s.fan_count} fans operational — "
                    "air circulation below safe minimum"
                ),
                "subsystem": "eclss",
            })

        return events


